// Run only against a fresh, local preview database. Never targets hosted data.
import assert from 'node:assert/strict';
import {report} from '../lib/merit.ts';
const base=process.env.MERIT_TEST_URL||'http://127.0.0.1:5173';
assert(['127.0.0.1','localhost'].includes(new URL(base).hostname),'Integration test must use loopback');
const auth=await fetch(base+'/signin-with-chatgpt?return_to=/',{redirect:'manual'});
const cookie=auth.headers.getSetCookie().map(c=>c.split(';')[0]).join('; ');
assert(cookie,'Local sign-in cookie is required; run the development preview');
let res=await fetch(base+'/api/workspace');assert.equal(res.status,401,'Unauthenticated calls must fail');
const read=async()=>{const r=await fetch(base+'/api/workspace',{headers:{Cookie:cookie}});assert.equal(r.status,200);return r.json()};
let data=await read();
assert.equal(data.state.projects.length,0,'Use a fresh local database to run this integration test');
const admin=data.actor;
const send=async(type,payload,revision=data.revision)=>fetch(base+'/api/workspace',{method:'POST',headers:{Cookie:cookie,Origin:base,'Content-Type':'application/json'},body:JSON.stringify({revision,command:{type,data:payload}})});
const write=async(type,payload)=>{const r=await send(type,payload);const x=await r.json();assert.equal(r.status,200,JSON.stringify(x));data=x;return x};
await write('employee.save',{name:'验收成员',department:'验收测试',email:'test.member@example.com',role:'member',active:true});
const member=data.state.employees.find(e=>e.email==='test.member@example.com');
await write('project.save',{code:'QA-LOCAL-001',name:'本地验收项目',client:'测试数据，不用于正式业务',contract:38000000,fund:38000000,owner:admin.id,start:'2026-01',end:'2026-12',members:[{employeeId:admin.id,coefficient:7000},{employeeId:member.id,coefficient:3000}],exception:''});
const p=data.state.projects[0];
await write('plan.save',{projectId:p.id,month:'2026-10',budget:1000,entries:[{employeeId:admin.id,rate:700},{employeeId:member.id,rate:300}],note:'本地端到端验收'});
const a=data.state.plans[0];
assert.equal(report(data.state,'2026-10')[0].points,0,'Drafts must not count');
res=await send('plan.save',{...a,entries:[{employeeId:admin.id,rate:9000}]});assert.equal(res.status,400,'Over-allocation must fail server-side');
await write('plan.publish',{id:a.id});
assert.equal(report(data.state,'2026-10').find(r=>r.employee.id===admin.id).points,2660000);
assert.equal(report(data.state,'2026-10').find(r=>r.employee.id===member.id).points,1140000);
assert.equal((await read()).state.plans[0].status,'published','Published data must persist across fresh requests');
res=await send('plan.reopen',{id:a.id},data.revision-1);assert.equal(res.status,409,'Stale writes must fail');
res=await fetch(base+'/api/workspace',{method:'POST',headers:{Cookie:cookie,Origin:'https://untrusted.example','Content-Type':'application/json'},body:'{}'});assert.equal(res.status,403,'Cross-origin writes must fail');
const revision=data.revision;
const both=await Promise.all([send('plan.reopen',{id:a.id},revision),send('plan.reopen',{id:a.id},revision)]);
assert.deepEqual(both.map(r=>r.status).sort(),[200,409],'Only one concurrent write may win');
data=await read();assert.equal(data.state.plans[0].status,'draft');assert.equal(report(data.state,'2026-10')[0].points,0);
await write('plan.delete',{id:a.id});await write('project.archive',{id:p.id});
assert.equal((await read()).state.projects[0].status,'archived');
console.log('PASS: authentication, persistence, project creation, draft, publication, monthly sum, server caps, stale revision, CSRF, concurrent writes, reopen and archive.');
